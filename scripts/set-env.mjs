/**
 * Writes src/environments/environment.prod.ts from the API_URL environment variable.
 * Runs automatically before `npm run build` (npm "prebuild" hook), so on Vercel the API URL
 * is configured in Settings → Environment Variables instead of in the code.
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const target = fileURLToPath(new URL('../src/environments/environment.prod.ts', import.meta.url));
const fallback = 'http://localhost:5058';

let apiUrl = process.env.API_URL?.trim();

if (!apiUrl) {
  if (process.env.VERCEL) {
    console.error('✗ Falta la variable API_URL. Agrégala en Vercel → Settings → Environment Variables.');
    process.exit(1);
  }
  console.warn(`⚠ API_URL no está definida; el build usará ${fallback}.`);
  apiUrl = fallback;
}

let url;
try {
  url = new URL(apiUrl);
} catch {
  console.error(`✗ API_URL no es una URL válida: "${apiUrl}"`);
  process.exit(1);
}
if (url.protocol !== 'https:' && url.protocol !== 'http:') {
  console.error(`✗ API_URL debe empezar con https:// (recibido: "${apiUrl}")`);
  process.exit(1);
}

apiUrl = apiUrl.replace(/\/+$/, '');

writeFileSync(
  target,
  `// Generated by scripts/set-env.mjs from API_URL. Do not edit: changes are overwritten on build.
export const environment = {
  apiUrl: ${JSON.stringify(apiUrl)},
};
`,
);

console.log(`✓ environment.prod.ts → apiUrl = ${apiUrl}`);
